#!/usr/bin/env python3
"""Write docs/SmogonSpriteCredits.md: who drew each Smogon Sprite Project sprite in the "Gen5-9 Sprites" part 1 pack.

The pack's 96x96 files (CITATIONS.md) come from the Smogon Sprite Project. The projects credit each Pokemon's sprites
in a sheet of finished sprites, linked from each project's Smogon thread: X/Y (Gen 6), Sun/Moon (Gen 7), and the
Smogon Sprite Project's Gen 8 and Gen 9 sheets. Snapshots of those sheets are in assets/sprites/credits/smogon/ (CSV,
as Google Sheets exports them). For each species with a 96x96 file in the pack, the doc lists the files and the
spriters and QC that its sheet gives for the species' base form (the first row with its dex number).

Usage: python3 tools/sprites/smogon_credits.py [--fetch]
--fetch downloads the sheets again first (needs the network).
"""
import csv
import os
import sys
import urllib.request

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
PACK = os.path.join(ROOT, "assets", "sprites", "packs", "gen5_9_part1")
CREDITS = os.path.join(ROOT, "assets", "sprites", "credits", "smogon")
OUT = os.path.join(ROOT, "docs", "SmogonSpriteCredits.md")
# (snapshot, the project, its thread, the sheet's ID, the first dex number it covers)
SHEETS = [
    ("gen6.csv", "X/Y Sprite Project", "https://www.smogon.com/forums/threads/x-y-sprite-project.3486712/",
     "1Gn0UORn-unvcbUeQhQdEBz0ADNcH49BZZqQ1dpXm9eo", 650),
    ("gen7.csv", "Sun/Moon Sprite Project", "https://www.smogon.com/forums/threads/sun-moon-sprite-project.3577711/",
     "1FMcHbSKEWZc7v2Ur4cyJjT_NhO0gqXyU9kDhsOQhlBQ", 722),
    ("gen8.csv", "Smogon Sprite Project (Gen 8)", "https://www.smogon.com/forums/threads/smogon-sprite-project.3647722/",
     "1acgzAjh0dnFRQnjZu8kSjS177rKCzpFfEHRLtwuuXRU", 810),
    ("gen9.csv", "Smogon Sprite Project (Gen 9)", "https://www.smogon.com/forums/threads/smogon-sprite-project.3647722/",
     "1MCjDktTOOFjLKM5C-RW6SfBQGkjlxDSCZAZDma_ItuA", 906),
]
KINDS = [("front", "front"), ("back", "back"), ("shiny_front", "shiny front"), ("shiny_back", "shiny back")]
SIZE = (96, 96)


def sheet_url(sheet_id):
    return f"https://docs.google.com/spreadsheets/d/{sheet_id}/edit"


def fetch():
    os.makedirs(CREDITS, exist_ok=True)
    for name, _, _, sheet_id, _ in SHEETS:
        url = f"https://docs.google.com/spreadsheets/d/{sheet_id}/export?format=csv"
        with urllib.request.urlopen(url) as response, open(os.path.join(CREDITS, name), "wb") as f:
            f.write(response.read())


def credits():
    """{dex: (spriter, QC, the sheet's index in SHEETS)}, from each sheet's first row for that dex number."""
    out = {}
    for i, (name, *_) in enumerate(SHEETS):
        rows = list(csv.reader(open(os.path.join(CREDITS, name), encoding="utf-8")))
        header = next(r for r in rows if "Spriter" in r)
        spriter, qc = header.index("Spriter"), header.index("QC")
        for row in rows:
            if row and row[0].isdigit() and int(row[0]) not in out:
                cell = (lambda k: row[k].strip() if k < len(row) else "")
                out[int(row[0])] = (cell(spriter), cell(qc), i)
    return out


def smogon_files():
    """[(dex, species name, [the kinds of its 96x96 files])] in the pack."""
    out = []
    for d in sorted(os.listdir(PACK)):
        dex, _, name = d.partition("-")
        if not dex.isdigit():
            continue
        kinds = [label for fn, label in KINDS if os.path.exists(os.path.join(PACK, d, fn + ".png"))
                 and Image.open(os.path.join(PACK, d, fn + ".png")).size == SIZE]
        if kinds:
            out.append((int(dex), name, kinds))
    return out


def cell(text):
    return text.replace("|", "\\|") if text else "—"


def main():
    if "--fetch" in sys.argv[1:]:
        fetch()
    by_dex = credits()
    files = smogon_files()
    lines = [
        "# Smogon Sprite Project credits",
        "",
        "_Generated by `tools/sprites/smogon_credits.py`. Do not edit by hand._",
        "",
        f"The \"Gen5-9 Sprites\" part 1 pack's 96×96 sprites ({sum(len(k) for _, _, k in files)} files, for "
        f"{len(files)} species) come from the Smogon Sprite Project (`CITATIONS.md`). Each row gives the sprites we "
        "have and the spriters and QC (quality checkers) that the project credits for the species, from its sheet "
        "of finished sprites:",
        "",
    ]
    for _, project, thread, sheet_id, first in SHEETS:
        lines.append(f"- **{project}** (#{first} on): thread {thread}, sheet {sheet_url(sheet_id)}")
    lines += [
        "",
        "Snapshots of the sheets are in `assets/sprites/credits/smogon/`. A spriter's note such as \"(shiny)\" or "
        "\"(back)\" is the sheet's own.",
        "",
        "| # | Species | Our sprites | Spriter | QC |",
        "|---|---|---|---|---|",
    ]
    missing = []
    for dex, name, kinds in files:
        spriter, qc, _ = by_dex.get(dex, ("", "", None))
        if not spriter:
            missing.append(f"#{dex} {name}")
        lines.append(f"| {dex} | {name} | {', '.join(kinds)} | {cell(spriter)} | {cell(qc)} |")
    if missing:
        lines += ["", "No spriter in the sheet: " + ", ".join(missing) + "."]
    open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"Wrote {os.path.relpath(OUT, ROOT)}: {len(files)} species, {len(missing)} with no spriter listed")


if __name__ == "__main__":
    main()

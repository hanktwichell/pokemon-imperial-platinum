#!/usr/bin/env python3
"""Render docs/MegaEvolution.md from data/megas.csv and data/mega_stones.yaml.

Checks that every Mega/Primal trigger item has exactly one source, and (with --decomp) that
every field replacement names a real visible-item script in pret/pokeplatinum.

Usage: python3 tools/design/gen_mega_doc.py [--decomp /path/to/pokeplatinum]
"""
import argparse
import csv
import os
import sys
from collections import Counter

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))

# Mega abilities that do not exist in the Gen IV engine, ordered by implementation priority:
# abilities used by boss trainers first.
BOSS_ABILITIES = ["Magic Bounce", "Parental Bond", "Strong Jaw", "Tough Claws", "Aura Guard"]

INTRO = """# Sovereign Platinum — Mega Evolution & Primal Reversion

> Generated by `tools/design/gen_mega_doc.py` from `data/megas.csv` (PokeAPI data) and `data/mega_stones.yaml`.
> Edit those files, not this one.

## How it works in Sovereign Platinum

- **Unlock.** No opponent Mega Evolves before **Commander Jupiter** in the Team Galactic Eterna Building. Beating **Leader
  Fantina** (the next Gym) gives the player the **Mega Ring** key item along with the Relic Badge, which sets
  `FLAG_SOVEREIGN_MEGA_UNLOCKED`. Stones picked up earlier can be held, but the Mega option stays hidden until then.
- **In battle.** When a Pokémon holding its Mega Stone is chosen to Fight, the move menu shows a **MEGA** toggle on the touch
  screen (Gen VI style; owner-confirmed, 2026-10-22). Mega Evolution happens at the start of the turn, before any moves, and the Mega's Speed applies
  from that turn (Gen VII+ rule). One Mega per trainer per battle. A Mega stays Mega until the battle ends or it faints, and
  reverts afterwards.
- **Primal Reversion.** Kyogre holding the Blue Orb / Groudon holding the Red Orb revert automatically on switch-in, with no
  button, no Mega Ring needed and no once-per-battle limit (owner-confirmed, 2026-10-22).
- **Mega Rayquaza** needs to know **Dragon Ascent** (taught post-game) instead of holding a stone, and must not be holding
  a Mega Stone.
- **Mega Stones can't be removed** by Knock Off, Thief, Covet, Trick or Switcheroo from a Pokémon that can use them, and
  can't be Flung.
- **Trainer AI.** Trainers with a Mega Evolve the first turn their Mega is on the field. In multi/tag battles each opposing
  trainer may Mega Evolve once.
- **Wild Pokémon** never Mega Evolve.

## Mega Evolution animation (target spec)

Modelled on how Pokémon Unbound and Pokémon Insurgence present Mega Evolution (credited in `CITATIONS.md`); all assets
will be original or credited.

1. Battle text: *"<Trainer>'s Mega Ring is reacting to <Pokémon>'s <Stone>!"* (player) or *"<Pokémon>'s <Stone> is
   reacting to <Trainer>'s Key Stone!"* (opponent).
2. Background darkens (palette fade to ~40 % brightness); the other battlers dim.
3. Two light streams (Key Stone colour → stone colour) arc from the trainer side to the Pokémon, with rainbow particles.
4. A sphere of prismatic light grows over the Pokémon and pulses three times while the screen gently shakes.
5. The sphere shatters into shards (white flash, 2 frames). The Mega sprite is swapped in during the flash.
6. The Mega Evolution symbol flashes over the sprite; the Mega's cry plays (pitch-shifted base cry until custom cries exist).
7. Text: *"<Pokémon> has Mega Evolved into Mega <Pokémon>!"*, and a Mega icon is drawn on the HP bar.

Primal Reversion uses the same structure, with a red (Ω) or blue (α) sphere and symbol instead of the rainbow.
Implementation: a new battle-animation script plus particle resources (`.spa`), driven by a battle subscript like the one the
engine uses for form changes (see `TechnicalDesign.md`).

## Abilities

Many Mega abilities don't exist in Platinum's battle engine. Until one is implemented, the Mega **keeps its pre-Mega
ability** (marked ⚙ below). Implementation priority — abilities used by boss trainers first:
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--decomp", help="path to a pret/pokeplatinum checkout (validates item script names)")
    args = ap.parse_args()
    megas = list(csv.DictReader(open(os.path.join(ROOT, "data", "megas.csv"), encoding="utf-8")))
    src = yaml.safe_load(open(os.path.join(ROOT, "data", "mega_stones.yaml"), encoding="utf-8"))

    sources = {}
    count = Counter()
    for f in src["field"]:
        sources[f["stone"]] = f"Field item — {f['location']} (replaces {f['replaces']})"
        count[f["stone"]] += 1
    for v in src["vendors"]:
        for s in v["stock"]:
            sources[s] = f"{v['name']} — ${v['price']:,}"
            count[s] += 1
    for e in src["events"]:
        sources[e["item"]] = e["source"]
        count[e["item"]] += 1

    errors = []
    needed = {m["trigger_item"] for m in megas}
    for item in sorted(needed):
        if count[item] != 1:
            errors.append(f"{item}: {count[item]} sources (need exactly 1)")
    for item in count:
        if item not in needed:
            errors.append(f"{item}: listed but no Mega uses it")
    if args.decomp:
        scripts = open(os.path.join(args.decomp, "res/field/scripts/scripts_visible_items.s"), encoding="utf-8").read()
        for f in src["field"]:
            if f"ScriptEntry {f['script']}\n" not in scripts:
                errors.append(f"{f['stone']}: script {f['script']} not found in pokeplatinum")

    L = [INTRO]
    non_gen4 = sorted({m["ability"] for m in megas if m["ability_in_gen4_engine"] == "0" and m["ability"]})
    L.append("1. " + ", ".join(f"**{a}**" for a in BOSS_ABILITIES) + " (boss trainers)")
    L.append("2. " + ", ".join(a for a in non_gen4 if a not in BOSS_ABILITIES) + "\n")
    blanks = [m["form"] for m in megas if not m["ability"]]
    if blanks:
        L.append("PokeAPI has no ability listed for: " + ", ".join(blanks) + ". These need checking against official "
                 "Legends: Z-A data before implementation.\n")

    L.append("## Every Mega Evolution and Primal Reversion\n")
    L.append(f"{len(megas)} forms. Stats, types and abilities come from PokeAPI. Forms marked † are new in Legends: Z-A or its "
             "Mega Dimension DLC.\n")
    L.append("| Form | Stone | Types | Ability | BST | HP/Atk/Def/SpA/SpD/Spe | Where to get the stone |")
    L.append("|---|---|---|---|---|---|---|")
    for m in megas:
        dag = " †" if "Z-A" in m["source_game"] else ""
        ab = (m["ability"] or "TBD") + (" ⚙" if m["ability_in_gen4_engine"] == "0" else "")
        stats = "/".join(m[k] for k in ("hp", "atk", "def", "spa", "spd", "spe"))
        L.append(f"| {m['form']}{dag} | {m['trigger_item']} | {m['types']} | {ab} | {m['bst']} | {stats} | "
                 f"{sources.get(m['trigger_item'], '**MISSING**')} |")
    L.append("")

    L.append("## Mega Stones hidden in the field\n")
    L.append("Each replaces a low-value pickup (never a TM, evolution stone or held item). Script names are from the "
             "vanilla Platinum decompilation; confirm each against the Renegade ROM in DSPRE before editing.\n")
    L.append("| Stone | Location | Replaces | Vanilla script | Why here |")
    L.append("|---|---|---|---|---|")
    for f in src["field"]:
        L.append(f"| {f['stone']} | {f['location']} | {f['replaces']} | `{f['script']}` | {f['why']} |")
    L.append("")

    L.append("## Mega Stone vendors\n")
    for v in src["vendors"]:
        L.append(f"### {v['name']}")
        L.append(f"- **Location:** {v['location']}")
        L.append(f"- **Available:** {v['unlock']}")
        L.append(f"- **Price:** ${v['price']:,} each, unlimited stock")
        L.append(f"- **Sells:** {', '.join(v['stock'])}\n")

    L.append("## Other sources\n")
    L.append(f"- **{src['key_item']['name']}:** {src['key_item']['source']} Unlocks {src['key_item']['unlocks']}")
    for e in src["events"]:
        L.append(f"- **{e['item']}:** {e['source']}")
    L.append("")

    with open(os.path.join(ROOT, "docs", "MegaEvolution.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    for e in errors:
        print("ERROR", e)
    print(f"{len(megas)} forms, {len(needed)} trigger items, {len(errors)} errors")
    sys.exit(1 if errors else 0)


if __name__ == "__main__":
    main()

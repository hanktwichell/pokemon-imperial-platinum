#!/usr/bin/env python3
"""Generate decomp/include/data/level_caps.h from data/level_caps.yaml.

Checks every `check` entry against the ace (highest level) of the matching team in
data/trainers_sovereign.yaml, that levels never decrease, and that every trainer constant
exists in decomp/generated/trainers.txt.

Usage: python3 tools/engine/gen_level_caps.py
"""
import os
import sys

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def ace_levels():
    data = yaml.safe_load(open(os.path.join(ROOT, "data", "trainers_sovereign.yaml"), encoding="utf-8"))
    aces = {}
    for t in data["story"]:
        aces[(t["trainer"], t.get("location", ""))] = max(m["level"] for m in t["team"])
    for t in data["league"]:
        teams = [t[f] for f in ("singles", "doubles") if f in t]
        aces[(t["trainer"], f"round {t['round']}")] = max(m["level"] for team in teams for m in team)
    return aces


def main():
    caps = yaml.safe_load(open(os.path.join(ROOT, "data", "level_caps.yaml"), encoding="utf-8"))["caps"]
    known = set(open(os.path.join(ROOT, "decomp", "generated", "trainers.txt")).read().split())
    aces = ace_levels()
    errors = []
    prev = 0
    for c in caps:
        if ("trainers" in c) == ("any" in c):
            errors.append(f"{c['label']}: give exactly one of `trainers` or `any`")
        for t in c.get("trainers", []) + c.get("any", []):
            if t not in known:
                errors.append(f"{c['label']}: unknown trainer {t}")
        if "check" in c:
            want = aces.get(tuple(c["check"]))
            if want is None:
                errors.append(f"{c['label']}: no team {c['check']} in trainers_sovereign.yaml")
            elif want != c["level"]:
                errors.append(f"{c['label']}: level {c['level']} but the ace in trainers_sovereign.yaml is Lv. {want}")
        if c["level"] < prev:
            errors.append(f"{c['label']}: cap goes down ({prev} -> {c['level']})")
        prev = c["level"]
    for e in errors:
        print("ERROR", e)
    if errors:
        sys.exit(1)

    most = max(len(c.get("trainers") or c["any"]) for c in caps)
    L = ["// Generated by tools/engine/gen_level_caps.py from data/level_caps.yaml. Do not edit.",
         "#ifndef POKEPLATINUM_DATA_LEVEL_CAPS_H", "#define POKEPLATINUM_DATA_LEVEL_CAPS_H", "",
         '#include "generated/trainers.h"', "",
         "// A step is cleared once every listed trainer has been defeated (LEVEL_CAP_ALL), or once any",
         "// one of them has (LEVEL_CAP_ANY, used for the rival's starter variants).",
         f"#define LEVEL_CAP_MAX_TRAINERS_PER_STEP {most}", "",
         "enum LevelCapStepMode {",
         "    LEVEL_CAP_ALL = 0,",
         "    LEVEL_CAP_ANY,",
         "};", "",
         "typedef struct LevelCapStep {",
         "    u16 trainers[LEVEL_CAP_MAX_TRAINERS_PER_STEP]; // TRAINER_NONE = unused",
         "    u8 mode;",
         "    u8 level;",
         "} LevelCapStep;", "",
         "static const LevelCapStep sLevelCapSteps[] = {"]
    for c in caps:
        listed = c.get("trainers") or c["any"]
        ts = listed + ["TRAINER_NONE"] * (most - len(listed))
        mode = "LEVEL_CAP_ANY" if "any" in c else "LEVEL_CAP_ALL"
        L.append(f"    {{ {{ {', '.join(ts)} }}, {mode}, {c['level']} }}, // {c['label']}")
    L += ["};", "", "#endif // POKEPLATINUM_DATA_LEVEL_CAPS_H", ""]
    out = os.path.join(ROOT, "decomp", "include", "data", "level_caps.h")
    open(out, "w").write("\n".join(L))
    print(f"wrote {out} ({len(caps)} steps)")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Write the Regional Forms Park's encounter tables (decision 22) from data/regional_forms_park.yaml:
decomp/include/data/regional_forms_park.h, read by src/overlay006/wild_encounters.c, and docs/RegionalFormsPark.md.

Form numbers come from tools/engine/gen_forms.py, so a form named in the YAML must be one it builds.

Usage: python3 tools/engine/gen_regional_forms_park.py
"""
import os
import sys

import yaml

sys.path.insert(0, os.path.dirname(__file__))
import gen_forms  # noqa: E402
from gen_items import DECOMP, ROOT  # noqa: E402

OUT = os.path.join(DECOMP, "include", "data", "regional_forms_park.h")
DOC = os.path.join(ROOT, "docs", "RegionalFormsPark.md")
QUADRANTS = 4
PLACES = {
    "Alola": "the field (south-west)",
    "Galar": "the forest (north-west)",
    "Hisui": "the mountain and its lake (north-east)",
    "Paldea": "the sea (south-east)",
}

DOC_INTRO = """# Regional Forms Park

Generated by `tools/engine/gen_regional_forms_park.py` from `data/regional_forms_park.yaml`. Do not edit.

Pal Park's grounds on Route 221 are the **Regional Forms Park** (decision 22, `ProjectStatus.md`), a free-roaming
wild area where the regional forms live.
- **Opening.** It opens after the Hall of Fame, like the rest of Route 221's park.
- **Visiting.** There's no Catching Show. The player talks to the lobby worker, walks in, and catches with their own
  Poké Balls. The worker inside the gate, or stepping into the gate, takes the player back out.
- **Encounters.** Each quadrant of the map is one region's zone. An encounter works like any route's (same step rates,
  Repel, abilities), but the Pokémon is picked from the zone's list by its odds, at a random level in its range.

**Proposal:** the zones' contents, odds and levels are the owner's call. This first version:
- keeps each region's forms in its own zone;
- makes evolved forms rarer;
- gives the Galarian birds 1% each (decision 22).
"""


def main():
    data = yaml.safe_load(open(os.path.join(ROOT, "data", "regional_forms_park.yaml"), encoding="utf-8"))
    forms = {f["ident"]: f for f in gen_forms.load_rows() if "ident" in f}
    zones = data["zones"]
    if len(zones) != QUADRANTS:
        sys.exit(f"regional_forms_park.yaml: {len(zones)} zones, want one per quadrant ({QUADRANTS})")

    tables, rows = [], []
    for zone in zones:
        refs = []
        for terrain in ("grass", "water"):
            name = f"sRegionalFormsPark{zone['name']}{terrain.capitalize()}"
            entries = []
            for ident, weight, lo, hi in zone[terrain] or []:
                if ident not in forms:
                    sys.exit(f"{zone['name']} {terrain}: {ident} isn't a form gen_forms.py builds")
                f = forms[ident]
                if not (1 <= weight <= 255 and 1 <= lo <= hi <= 100):
                    sys.exit(f"{zone['name']} {terrain}: {ident} has a bad weight or level range")
                entries.append(f"    {{ {f['species']}, {f['number']}, {weight}, {lo}, {hi} }}, // {f['name']}\n")
            if not entries:  # this quadrant has no such terrain
                refs.append("NULL, 0")
                continue
            tables.append(f"static const RegionalFormsParkEntry {name}[] = {{\n{''.join(entries)}}};\n")
            refs.append(f"{name}, NELEMS({name})")
        rows.append(f"    {{ {refs[0]}, {refs[1]} }}, // {zone['name']}\n")

    text = f"""// Generated by tools/engine/gen_regional_forms_park.py from data/regional_forms_park.yaml. Do not edit.
#ifndef POKEPLATINUM_DATA_REGIONAL_FORMS_PARK_H
#define POKEPLATINUM_DATA_REGIONAL_FORMS_PARK_H

#include "generated/species.h"

typedef struct RegionalFormsParkEntry {{
    u16 species;
    u8 form;
    u8 weight;
    u8 minLevel;
    u8 maxLevel;
}} RegionalFormsParkEntry;

typedef struct RegionalFormsParkZone {{
    const RegionalFormsParkEntry *grass;
    u8 grassCount;
    const RegionalFormsParkEntry *water;
    u8 waterCount;
}} RegionalFormsParkZone;

{chr(10).join(tables)}
// One zone per quadrant of the Pal Park map: north-west, north-east, south-west, south-east.
static const RegionalFormsParkZone sRegionalFormsParkZones[{QUADRANTS}] = {{
{''.join(rows)}}};

#endif // POKEPLATINUM_DATA_REGIONAL_FORMS_PARK_H
"""
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)

    doc = [DOC_INTRO]
    for zone in sorted(zones, key=lambda z: z["name"]):
        doc.append(f"\n## {zone['name']} — {PLACES[zone['name']]}\n")
        for terrain, label in (("grass", "Tall grass"), ("water", "Surfing and fishing")):
            entries = zone[terrain] or []
            if not entries:
                continue
            total = sum(e[1] for e in entries)
            doc.append(f"\n{label}:\n\n| Pokémon | Odds | Levels |\n|---|---|---|\n")
            for ident, weight, lo, hi in entries:
                name = forms[ident]["name"].removeprefix("Standard ")
                levels = f"{lo}" if lo == hi else f"{lo}–{hi}"
                doc.append(f"| {name} | {100 * weight / total:.0f}% | {levels} |\n")
    with open(DOC, "w", encoding="utf-8") as f:
        f.write("".join(doc))
    print(f"wrote {OUT}: {sum(len(z['grass']) + len(z['water']) for z in zones)} entries in {len(zones)} zones")


if __name__ == "__main__":
    main()

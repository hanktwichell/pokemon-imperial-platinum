#!/usr/bin/env python3
"""Write the Totem trials' battle data (decision 18) from data/totem_trials.yaml:
  decomp/include/data/sovereign_totem_trials.h       each trial's Totem, aura and helpers (src/encounter.c)
  decomp/include/constants/sovereign_totem_trials.h  TOTEM_TRIAL_<SPECIES>, the trial numbers scripts pass to
                                                     SovereignStartTotemTrial
  docs/TotemTrials.md                                the trials, for review

The Totem takes its Totem form, and a helper named after a form ("Alolan Rattata") takes that form; the form numbers
come from tools/engine/gen_forms.py. Helpers are 2 levels below the Totem.

Usage: python3 tools/engine/gen_totem_trials.py
"""
import csv
import os
import re
import sys

import yaml

sys.path.insert(0, os.path.dirname(__file__))
import gen_forms  # noqa: E402
from gen_items import DECOMP, ROOT, stem_of  # noqa: E402

HELPER_LEVELS_BELOW = 2
HELPER_COUNT = 3  # one on the field from the start, then two reserves
# The aura's stats, in the battle's stat order (BATTLE_STAT_ATTACK onwards; BATTLE_STATUS_TOTEM_AURA in battle.h).
AURA_STATS = ["atk", "def", "spe", "spa", "spd"]


def parse_boost(boost):
    m = re.fullmatch(r"(atk|def|spe|spa|spd|all)\+([1-6])", boost.strip())
    if not m:
        sys.exit(f"totem_trials.yaml: bad boost {boost!r} (want e.g. def+1 or all+1)")
    stats = AURA_STATS if m.group(1) == "all" else [m.group(1)]
    return [int(m.group(2)) if s in stats else 0 for s in AURA_STATS]


def main():
    trials = yaml.safe_load(open(os.path.join(ROOT, "data", "totem_trials.yaml"), encoding="utf-8"))["trials"]
    forms = gen_forms.load_rows()
    by_ident = {f["ident"]: f for f in forms if "ident" in f}
    by_name = {f["name"]: f for f in forms if "ident" in f}
    fm_rows = list(csv.DictReader(open(os.path.join(ROOT, "data", "forms.csv"), encoding="utf-8")))
    # A Totem's form: its species' first Totem form (Mimikyu: Disguised); "Marowak (Alolan)" is Marowak's.
    totem_forms = {}
    for row in fm_rows:
        if row["category"] == "totem" and row["base_species"] not in totem_forms:
            totem_forms[row["base_species"]] = by_ident[row["identifier"]]
    species = set(open(os.path.join(DECOMP, "generated", "species.txt"), encoding="utf-8").read().split())

    def mon(name, level, totem=False):
        if totem:
            form = totem_forms.get(re.sub(r" \(.*\)$", "", name))
            if form is None:
                sys.exit(f"totem_trials.yaml: {name} has no Totem form in data/forms.csv")
            return form["species"], form["number"], level, form["name"]
        if name in by_name:
            form = by_name[name]
            return form["species"], form["number"], level, name
        const = "SPECIES_" + stem_of(name).upper()
        if const not in species:
            sys.exit(f"totem_trials.yaml: unknown species {name}")
        return const, 0, level, name

    rows, consts, doc_rows = [], [], []
    for i, t in enumerate(trials):
        helpers = t["helpers"]
        if len(helpers) != HELPER_COUNT:
            sys.exit(f"totem_trials.yaml: {t['totem']} needs {HELPER_COUNT} helpers")
        totem = mon(t["totem"], t["level"], totem=True)
        aura = parse_boost(t["boost"])
        helper_rows = [mon(h, t["level"] - HELPER_LEVELS_BELOW) for h in helpers]

        def fmt(m):
            return f"{{ {m[0]}, {m[1]}, {m[2]} }}"

        rows.append(f"    // {totem[3]}, {t['location']} (aura {t['boost']})\n"
                    f"    {{ {fmt(totem)}, {{ {', '.join(map(str, aura))} }}, "
                    f"{{ {', '.join(fmt(h) for h in helper_rows)} }} }},\n")
        doc_rows.append(f"| {i + 1} | {totem[3]} | {t['level']} | {t['location']} | {t['after']} | {t['aura']} | "
                        f"{', '.join(h[3] for h in helper_rows)} (Lv. {t['level'] - HELPER_LEVELS_BELOW}) | "
                        f"{t.get('map', 'not yet')} |\n")
        consts.append(f"#define TOTEM_TRIAL_{stem_of(re.sub(r' [(].*', '', t['totem'])).upper():<12} {i}\n")

    header = "// Generated by tools/engine/gen_totem_trials.py from data/totem_trials.yaml. Do not edit.\n"
    with open(os.path.join(DECOMP, "include", "constants", "sovereign_totem_trials.h"), "w", encoding="utf-8") as f:
        f.write(f"""{header}#ifndef POKEPLATINUM_CONSTANTS_SOVEREIGN_TOTEM_TRIALS_H
#define POKEPLATINUM_CONSTANTS_SOVEREIGN_TOTEM_TRIALS_H

{''.join(consts)}
#define SOVEREIGN_TOTEM_TRIAL_COUNT  {len(trials)}
#define SOVEREIGN_TOTEM_HELPER_COUNT {HELPER_COUNT}

#endif // POKEPLATINUM_CONSTANTS_SOVEREIGN_TOTEM_TRIALS_H
""")
    with open(os.path.join(DECOMP, "include", "data", "sovereign_totem_trials.h"), "w", encoding="utf-8") as f:
        f.write(f"""{header}#ifndef POKEPLATINUM_DATA_SOVEREIGN_TOTEM_TRIALS_H
#define POKEPLATINUM_DATA_SOVEREIGN_TOTEM_TRIALS_H

#include "constants/sovereign_totem_trials.h"
#include "generated/species.h"

typedef struct SovereignTotemTrialMon {{
    u16 species;
    u8 form;
    u8 level;
}} SovereignTotemTrialMon;

typedef struct SovereignTotemTrial {{
    SovereignTotemTrialMon totem;
    u8 aura[5]; // stat stages the aura raises: Attack, Defense, Speed, Sp. Atk, Sp. Def
    SovereignTotemTrialMon helpers[SOVEREIGN_TOTEM_HELPER_COUNT];
}} SovereignTotemTrial;

static const SovereignTotemTrial sSovereignTotemTrials[SOVEREIGN_TOTEM_TRIAL_COUNT] = {{
{''.join(rows)}}};

#endif // POKEPLATINUM_DATA_SOVEREIGN_TOTEM_TRIALS_H
""")
    with open(os.path.join(ROOT, "docs", "TotemTrials.md"), "w", encoding="utf-8") as f:
        f.write(f"""# Totem trials

Generated by `tools/engine/gen_totem_trials.py` from `data/totem_trials.yaml`. Do not edit.

The 11 Totem trials (decision 18, `ProjectStatus.md`) are one-time battles along the main story, all before the Elite
Four. Each is a wild double battle:
- **The start.** The Totem and its first helper are out from the start, and the Totem's aura raises its stats.
- **Helpers.** When a helper faints, the Totem calls the next one into the empty slot, up to 3 helpers in all. Once the
  Totem has fainted it calls no more.
- **Catching.** Poké Balls can be thrown only at a Pokémon left alone on its side. The Totem is caught in its Totem
  form.
- **No escape.** The player can't run, and Roar, Whirlwind, Teleport and the Poké Doll fail.

On the map the Totem stands as a huge Pokémon (its 64x64 overworld sprite, `tools/sprites/make_totem_overworld.py`).
Talking to it starts the trial (`CommonScript_SovereignTotemTrial` in `scripts_common.s`):
- **Two Pokémon.** Until a lone Pokémon can fight a double battle 1 vs 2, the trial needs two that can battle.
- **Win or catch.** The trial is done (its `FLAG_SOVEREIGN_TOTEM_TRIAL_*` flag, which also hides the Totem), and the
  Totem leaves its crown piece on the ground (`docs/Story.md`, *The crown*). The 11th piece merges them into the Crown.
- **Lose.** The player blacks out and the Totem is back next time.
- **When it appears.** A Totem whose place opens before its trial does (the "After" column) stays hidden until that
  fight is won: the map's OnTransition script hides it with `FLAG_MAP_LOCAL_HIDE_TOTEM`.

The places, levels and auras are approved by the owner; the helpers are a proposal. The auras' stages marked "check"
come from a second guide where Serebii gives none.

| # | Totem | Level | Place | After | Aura | Helpers | On the map |
|---|---|---|---|---|---|---|---|
{''.join(doc_rows)}""")
    print(f"wrote {len(trials)} Totem trials")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Write Sovereign's rare wild encounters (decision 28: the Ultra Beasts and a few others) from
data/sovereign_rare_wild.yaml: decomp/include/data/sovereign_rare_wild.h, read by
decomp/src/overlay006/wild_encounters.c, and docs/RareWildEncounters.md.

Checks every species and map exists, that each map has wild encounters of the entry's terrain (a map with a rate of
0 never rolls), and that the rates on one map and terrain add up to 100 or less.

Usage: python3 tools/engine/gen_rare_wild.py
"""
import json
import os
import re
import sys

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DECOMP = os.path.join(ROOT, "decomp")
DATA = os.path.join(ROOT, "data", "sovereign_rare_wild.yaml")
OUT = os.path.join(DECOMP, "include", "data", "sovereign_rare_wild.h")
DOC = os.path.join(ROOT, "docs", "RareWildEncounters.md")
TERRAINS = {"land": ("SOVEREIGN_RARE_WILD_LAND", "land_rate", "Tall grass / cave"),
            "surf": ("SOVEREIGN_RARE_WILD_SURF", "surf_rate", "Surfing")}


def title(ident):
    return " ".join(w.capitalize() for w in ident.split("_"))


def main():
    data = yaml.safe_load(open(DATA, encoding="utf-8"))
    species = set(open(os.path.join(DECOMP, "generated", "species.txt"), encoding="utf-8").read().split())
    headers = open(os.path.join(DECOMP, "include", "data", "map_headers.h"), encoding="utf-8").read()
    gates = data["gates"]
    errors, rows, doc_rows, totals = [], [], [], {}

    def encounter_rate(map_name, terrain):
        m = re.search(r"\[MAP_HEADER_%s\] = \{.*?\.wildEncountersArchiveID = (\w+)," % re.escape(map_name), headers, re.S)
        if not m:
            errors.append(f"{map_name}: no such map header")
            return 0
        path = os.path.join(DECOMP, "res", "field", "encounters", f"{m.group(1)}.json")
        if not os.path.exists(path):
            return 0
        return json.load(open(path, encoding="utf-8")).get(TERRAINS[terrain][1], 0)

    for e in data["encounters"]:
        sp, gate, terrain = e["species"], e["gate"], e["terrain"]
        lo, hi = (e["level"], e["level"]) if isinstance(e["level"], int) else e["level"]
        if f"SPECIES_{sp}" not in species:
            errors.append(f"{sp}: not a species")
        if gate not in gates:
            errors.append(f"{sp}: unknown gate {gate}")
        if terrain not in TERRAINS:
            errors.append(f"{sp}: terrain must be land or surf")
            continue
        if not (1 <= e["rate"] <= 100 and 1 <= lo <= hi <= 100):
            errors.append(f"{sp}: bad rate or level")
        g = gates.get(gate, {})
        caught = f"SPECIES_{g['caught']}" if "caught" in g else "SPECIES_NONE"
        for map_name in e["maps"]:
            if encounter_rate(map_name, terrain) == 0:
                errors.append(f"{sp}: {map_name} has no {terrain} encounters, so it would never roll")
            key = (map_name, terrain)
            totals[key] = totals.get(key, 0) + e["rate"]
            rows.append((map_name, f"    {{ MAP_HEADER_{map_name}, SPECIES_{sp}, {caught}, {g.get('chronicle', 0)}, "
                                   f"{TERRAINS[terrain][0]}, {e['rate']}, {lo}, {hi} }},\n"))
        levels = f"{lo}" if lo == hi else f"{lo}–{hi}"
        doc_rows.append(f"| {title(sp)} | {e['hint'][0].upper() + e['hint'][1:]} | {TERRAINS[terrain][2]} | "
                        f"{e['rate']}% | {levels} | {g.get('text', gate)} |\n")
    for (map_name, terrain), total in totals.items():
        if total > 100:
            errors.append(f"{map_name} {terrain}: rates add up to {total}%")
    if errors:
        sys.exit("sovereign_rare_wild.yaml:\n  " + "\n  ".join(errors))

    rows.sort(key=lambda r: r[0])
    text = f"""// Generated by tools/engine/gen_rare_wild.py from data/sovereign_rare_wild.yaml. Do not edit.
#ifndef POKEPLATINUM_DATA_SOVEREIGN_RARE_WILD_H
#define POKEPLATINUM_DATA_SOVEREIGN_RARE_WILD_H

#include "generated/species.h"

#include "generated/map_headers.h"

#define SOVEREIGN_RARE_WILD_LAND 0
#define SOVEREIGN_RARE_WILD_SURF 1

typedef struct SovereignRareWildEntry {{
    u16 mapHeaderID;
    u16 species;
    u16 caughtSpecies; // must be caught first (SPECIES_NONE: no need)
    u8 minChronicle; // VAR_SOVEREIGN_CHRONICLE at least this
    u8 terrain;
    u8 rate; // percent of the map's wild encounters of that terrain
    u8 minLevel;
    u8 maxLevel;
}} SovereignRareWildEntry;

static const SovereignRareWildEntry sSovereignRareWild[] = {{
{''.join(r[1] for r in rows)}}};

#endif // POKEPLATINUM_DATA_SOVEREIGN_RARE_WILD_H
"""
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)

    doc = ["# Rare wild encounters\n\n",
           "Generated by `tools/engine/gen_rare_wild.py` from `data/sovereign_rare_wild.yaml`. Do not edit.\n\n",
           "The Ultra Beasts aren't static encounters (decision 28, `ProjectStatus.md`). Each is ",
           "a rare wild Pokémon on its maps once its gate is met: the rate is the share of that map's wild encounters, ",
           "on the terrain shown. They can be met again after a catch. The Legend Archivist hints at the ones not caught ",
           "yet. No rare roll happens in a Poké Radar patch, with a partner or in the Safari Game. The Paradox Pokémon ",
           "come from the Oreburgh Mining Museum's two dealers instead (`PostgameLegendaries.md`).\n\n",
           "| Pokémon | Where | Terrain | Rate | Lv. | Appears once |\n|---|---|---|---|---|---|\n"]
    doc += doc_rows
    with open(DOC, "w", encoding="utf-8") as f:
        f.write("".join(doc))
    print(f"wrote {OUT}: {len(rows)} entries for {len(data['encounters'])} species")


if __name__ == "__main__":
    main()

    // An electric current ran across the battlefield!
    BufferMessage BattleStrings_Text_SovereignElectricTerrainStart, TAG_NONE
    UpdateVar OPCODE_FLAG_OFF, BTLVAR_FIELD_CONDITIONS, FIELD_CONDITION_TERRAIN|FIELD_CONDITION_TERRAIN_TURNS
    UpdateVar OPCODE_FLAG_ON, BTLVAR_FIELD_CONDITIONS, FIELD_CONDITION_TERRAIN_ELECTRIC|FIELD_CONDITION_TERRAIN_5_TURNS

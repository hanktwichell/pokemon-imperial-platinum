#include "macros/btlcmd.inc"


_000:
    PlayBattleAnimation BTLSCR_MSG_TEMP, BATTLE_ANIMATION_HELD_ITEM
    Wait 
    UpdateVar OPCODE_SET, BTLVAR_SIDE_EFFECT_PARAM, MOVE_SUBSCRIPT_PTR_QUARTER_RECOIL
    UpdateVarFromVar OPCODE_ADD, BTLVAR_SIDE_EFFECT_PARAM, BTLVAR_MSG_TEMP
    // Sovereign (item 11): Ripen makes a Berry's stat rise 2 stages.
    CheckAbility CHECK_NOT_HAVE, BTLSCR_MSG_BATTLER_TEMP, ABILITY_RIPEN, _sovereign_one_stage
    UpdateVar OPCODE_ADD, BTLVAR_SIDE_EFFECT_PARAM, MOVE_SUBSCRIPT_PTR_ATTACK_UP_2_STAGES - MOVE_SUBSCRIPT_PTR_ATTACK_UP_1_STAGE

_sovereign_one_stage:
    UpdateVar OPCODE_SET, BTLVAR_SIDE_EFFECT_TYPE, SIDE_EFFECT_TYPE_HELD_ITEM
    UpdateVarFromVar OPCODE_SET, BTLVAR_SIDE_EFFECT_MON, BTLVAR_MSG_BATTLER_TEMP
    Call BATTLE_SUBSCRIPT_UPDATE_STAT_STAGE
    Call BATTLE_SUBSCRIPT_PLUCK_CHECK
    End 

_000:
    CompareVarToValue OPCODE_FLAG_SET, BTLVAR_MOVE_STATUS_FLAGS, MOVE_STATUS_MISSED|MOVE_STATUS_SEMI_INVULNERABLE, _091
    // Sovereign (item 11): Gen IX's rules (the abilities that can't be copied or overwritten, the same ability)
    CompareVarToValue OPCODE_NEQ, BTLVAR_SOVEREIGN_ROLE_PLAY_FAILS, 0, _091
    // Sovereign (item 11): an Ability Shield keeps its holder's Ability
    CompareVarToValue OPCODE_NEQ, BTLVAR_SOVEREIGN_ABILITY_SHIELD_ATTACKER, 0, _sovereign_ability_shield
    Call BATTLE_SUBSCRIPT_ATTACK_MESSAGE_AND_ANIMATION
    UpdateVarFromVar OPCODE_SET, BTLVAR_SCRIPT_TEMP, BTLVAR_TOTAL_TURNS
    UpdateVar OPCODE_BITWISE_AND, BTLVAR_SCRIPT_TEMP, 1
    UpdateMonDataFromVar OPCODE_SET, BTLSCR_ATTACKER, BATTLEMON_TRUANT, BTLVAR_SCRIPT_TEMP
    UpdateMonDataFromVar OPCODE_GET, BTLSCR_DEFENDER, BATTLEMON_ABILITY, BTLVAR_SCRIPT_TEMP
    UpdateMonDataFromVar OPCODE_SET, BTLSCR_ATTACKER, BATTLEMON_ABILITY, BTLVAR_SCRIPT_TEMP
    CompareVarToValue OPCODE_NEQ, BTLVAR_SCRIPT_TEMP, 112, _081
    UpdateVarFromVar OPCODE_SET, BTLVAR_SCRIPT_TEMP, BTLVAR_TOTAL_TURNS
    UpdateVar OPCODE_ADD, BTLVAR_SCRIPT_TEMP, 1
    UpdateMonDataFromVar OPCODE_SET, BTLSCR_ATTACKER, BATTLEMON_SLOW_START_TURN_NUMBER, BTLVAR_SCRIPT_TEMP
    UpdateMonData OPCODE_SET, BTLSCR_ATTACKER, BATTLEMON_SLOW_START_ANNOUNCED, 0
    UpdateMonData OPCODE_SET, BTLSCR_ATTACKER, BATTLEMON_SLOW_START_FINISHED, 0


    // {0} copied {1}’s {2}!
    PrintMessage BattleStrings_Text_PokemonCopiedPokemonsAbility_AllyAlly, TAG_NICKNAME_NICKNAME_ABILITY, BTLSCR_ATTACKER, BTLSCR_DEFENDER, BTLSCR_DEFENDER

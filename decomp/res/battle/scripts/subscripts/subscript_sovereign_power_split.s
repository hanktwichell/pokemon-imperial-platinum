#include "macros/btlcmd.inc"

// Sovereign (item 11): Power Split. The user and the target average their Attack and Sp Attack.

_000:
    CompareVarToValue OPCODE_FLAG_SET, BTLVAR_MOVE_STATUS_FLAGS, MOVE_STATUS_MISSED|MOVE_STATUS_SEMI_INVULNERABLE, _fail
    Call BATTLE_SUBSCRIPT_ATTACK_MESSAGE_AND_ANIMATION
    UpdateMonDataFromVar OPCODE_GET, BTLSCR_ATTACKER, BATTLEMON_ATTACK, BTLVAR_CALC_TEMP
    UpdateMonDataFromVar OPCODE_GET, BTLSCR_DEFENDER, BATTLEMON_ATTACK, BTLVAR_HP_CALC_TEMP
    UpdateVarFromVar OPCODE_ADD, BTLVAR_CALC_TEMP, BTLVAR_HP_CALC_TEMP
    UpdateVar OPCODE_DIV, BTLVAR_CALC_TEMP, 2
    UpdateMonDataFromVar OPCODE_SET, BTLSCR_ATTACKER, BATTLEMON_ATTACK, BTLVAR_CALC_TEMP
    UpdateMonDataFromVar OPCODE_SET, BTLSCR_DEFENDER, BATTLEMON_ATTACK, BTLVAR_CALC_TEMP
    UpdateMonDataFromVar OPCODE_GET, BTLSCR_ATTACKER, BATTLEMON_SP_ATTACK, BTLVAR_CALC_TEMP
    UpdateMonDataFromVar OPCODE_GET, BTLSCR_DEFENDER, BATTLEMON_SP_ATTACK, BTLVAR_HP_CALC_TEMP
    UpdateVarFromVar OPCODE_ADD, BTLVAR_CALC_TEMP, BTLVAR_HP_CALC_TEMP
    UpdateVar OPCODE_DIV, BTLVAR_CALC_TEMP, 2
    UpdateMonDataFromVar OPCODE_SET, BTLSCR_ATTACKER, BATTLEMON_SP_ATTACK, BTLVAR_CALC_TEMP
    UpdateMonDataFromVar OPCODE_SET, BTLSCR_DEFENDER, BATTLEMON_SP_ATTACK, BTLVAR_CALC_TEMP
    // {0} shared its power with the target!
    PrintMessage BattleStrings_Text_SovereignSharedItsPower_Ally, TAG_NICKNAME, BTLSCR_ATTACKER
    Wait 
    WaitButtonABTime 30
    End 

_fail:
    UpdateVar OPCODE_FLAG_ON, BTLVAR_MOVE_STATUS_FLAGS, MOVE_STATUS_FAILED
    End 

#include "macros/btlcmd.inc"

// Sovereign (item 11): Gear Up raises the Attack and Sp. Atk of the user and its ally by 1 stage each, if they
// have Plus or Minus. It fails when neither does.

_000:
    UpdateVar OPCODE_SET, BTLVAR_CALC_TEMP, 0
    UpdateVarFromVar OPCODE_SET, BTLVAR_SIDE_EFFECT_MON, BTLVAR_ATTACKER
    CheckAbility CHECK_HAVE, BTLSCR_SIDE_EFFECT_MON, ABILITY_PLUS, _raise_user
    CheckAbility CHECK_NOT_HAVE, BTLSCR_SIDE_EFFECT_MON, ABILITY_MINUS, _ally

_raise_user:
    UpdateVar OPCODE_SET, BTLVAR_CALC_TEMP, 1
    UpdateVar OPCODE_SET, BTLVAR_SIDE_EFFECT_PARAM, MOVE_SUBSCRIPT_PTR_ATTACK_UP_1_STAGE
    Call BATTLE_SUBSCRIPT_UPDATE_STAT_STAGE
    UpdateVar OPCODE_SET, BTLVAR_SIDE_EFFECT_PARAM, MOVE_SUBSCRIPT_PTR_SP_ATTACK_UP_1_STAGE
    Call BATTLE_SUBSCRIPT_UPDATE_STAT_STAGE

_ally:
    CompareVarToValue OPCODE_FLAG_NOT, BTLVAR_BATTLE_TYPE, BATTLE_TYPE_DOUBLES, _check
    UpdateVarFromVar OPCODE_SET, BTLVAR_SIDE_EFFECT_MON, BTLVAR_ATTACKER
    UpdateVar OPCODE_BITWISE_XOR, BTLVAR_SIDE_EFFECT_MON, 2
    CompareMonDataToValue OPCODE_EQU, BTLSCR_SIDE_EFFECT_MON, BATTLEMON_CUR_HP, 0, _check
    CheckAbility CHECK_HAVE, BTLSCR_SIDE_EFFECT_MON, ABILITY_PLUS, _raise_ally
    CheckAbility CHECK_NOT_HAVE, BTLSCR_SIDE_EFFECT_MON, ABILITY_MINUS, _check

_raise_ally:
    UpdateVar OPCODE_SET, BTLVAR_CALC_TEMP, 1
    UpdateVar OPCODE_SET, BTLVAR_SIDE_EFFECT_PARAM, MOVE_SUBSCRIPT_PTR_ATTACK_UP_1_STAGE
    Call BATTLE_SUBSCRIPT_UPDATE_STAT_STAGE
    UpdateVar OPCODE_SET, BTLVAR_SIDE_EFFECT_PARAM, MOVE_SUBSCRIPT_PTR_SP_ATTACK_UP_1_STAGE
    Call BATTLE_SUBSCRIPT_UPDATE_STAT_STAGE

_check:
    CompareVarToValue OPCODE_NEQ, BTLVAR_CALC_TEMP, 0, _end
    UpdateVar OPCODE_FLAG_ON, BTLVAR_MOVE_STATUS_FLAGS, MOVE_STATUS_FAILED

_end:
    End 
